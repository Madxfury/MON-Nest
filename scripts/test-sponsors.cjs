const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const Module = require('node:module');
const ts = require('typescript');
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const filename = path.resolve('src/SponsorIntegrations.tsx');
const compiled = ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, jsx: ts.JsxEmit.ReactJSX } }).outputText;
const componentModule = new Module(filename, module);
componentModule.filename = filename;
componentModule.paths = Module._nodeModulePaths(path.dirname(filename));
componentModule._compile(compiled, filename);
const Component = componentModule.exports.default;
const connected = renderToStaticMarkup(React.createElement(Component, { alchemyConfigured: true }));
const unconfigured = renderToStaticMarkup(React.createElement(Component, { alchemyConfigured: false }));
assert.match(connected, /RPC connected/);
assert.match(connected, /APIs verified/);
assert.match(connected, /Chain 10143/);
assert.match(connected, /hosted indexer/);
assert.match(connected, /Not active in the rental flow/);
assert.doesNotMatch(connected, /Adapter ready|Live verification needs|public Monad RPC is the current fallback/);
assert.match(unconfigured, /Not configured/);
assert.doesNotMatch(unconfigured, /RPC connected/);
assert.match(connected, /No mainnet bridge or deposit is enabled/);
console.log('Sponsor UI: connected/fallback states, verified APIs, and pending integrations passed.');
